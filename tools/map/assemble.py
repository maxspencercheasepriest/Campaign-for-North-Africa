# Merge the five digitised map sections (A-E) into one game map module: src/shared/mapdata.js
# Sections are stacked west->east; row 34 of a section is the same hexrow as row 01 of the next.
# Game coordinates: c = column-1, r = 33*section + row - 1 (odd-q layout, north = +c).
import json, sys
SECTIONS = 'ABCDE'
CODES = {'sea': 's', 'clear': 'c', 'gravel': 'g', 'saltmarsh': 'm', 'heavyveg': 'v', 'rough': 'r', 'mountain': 'M',
         'delta': 'l', 'desert': 'd', 'majorcity': 'C', 'swamp': 'w'}
work = sys.argv[1]
out = sys.argv[2]
tiles = {}
sides = {}
def g(sec, key):
    col, row = int(key[:2]), int(key[2:])
    return (col - 1, 33 * sec + row - 1)
for s in range(5):
    d = json.load(open(f'{work}/dig-{s}.json'))
    for k, h in d['hexes'].items():
        c = g(s, k)
        # Overlap row: keep the first non-clear reading.
        if c in tiles and tiles[c] != 'c': continue
        tiles[c] = CODES[h['t']]
    for k, f in d['sides'].items():
        a, b = k.split('|')
        A, B = g(s, a), g(s, b)
        e = (min(A, B), max(A, B))
        rec = sides.setdefault(e, {})
        for kk, vv in f.items():
            if kk == 'down': rec['down'] = list(g(s, vv))
            else: rec.setdefault(kk, vv)
# Drop small islands of land (chart boxes printed on the sea) — the real coast is one connected landmass.
from collections import deque
def nb(c, r):
    return [(c, r - 1), (c, r + 1), (c - 1, r), (c + 1, r), (c - 1, r + (1 if c % 2 else -1)), (c + 1, r + (1 if c % 2 else -1))]
land = {k for k, v in tiles.items() if v != 's'}
seen = set()
for start in list(land):
    if start in seen: continue
    comp, q = {start}, deque([start]); seen.add(start)
    while q:
        x = q.popleft()
        for n in nb(*x):
            if n in land and n not in seen: seen.add(n); comp.add(n); q.append(n)
    if len(comp) < 40:
        for x in comp: del tiles[x]
maxc = max(c for c, r in tiles) + 1
maxr = max(r for c, r in tiles) + 1
grid = []
for c in range(maxc):
    grid.append(''.join(tiles.get((c, r), '_') for r in range(maxr)))
hexsides, roads, tracks, rails = [], [], [], []
for (A, B), f in sorted(sides.items()):
    if 'side' in f:
        rec = [A[0], A[1], B[0], B[1], f['side']]
        if 'down' in f: rec.append(0 if tuple(f['down']) == A else 1)
        hexsides.append(rec)
    if f.get('line') == 'road': roads.append([A[0], A[1], B[0], B[1]])
    elif f.get('line') == 'track': tracks.append([A[0], A[1], B[0], B[1]])
    if f.get('rail'): rails.append([A[0], A[1], B[0], B[1]])
# Linear features must form chains: drop isolated detections (map text, symbols) that aren't part of a route.
def chains(edges, minlen):
    adj = {}
    for e in edges:
        a, b = (e[0], e[1]), (e[2], e[3])
        adj.setdefault(a, []).append((b, e)); adj.setdefault(b, []).append((a, e))
    seen, keep = set(), []
    for e in edges:
        if id(e) in seen: continue
        comp, stack = [], [e]
        seen.add(id(e))
        while stack:
            x = stack.pop(); comp.append(x)
            for end in ((x[0], x[1]), (x[2], x[3])):
                for _, y in adj[end]:
                    if id(y) not in seen: seen.add(id(y)); stack.append(y)
        if len(comp) >= minlen: keep += comp
    return keep
roads, tracks, rails = chains(roads, 5), chains(tracks, 3), chains(rails, 10)
data = {'cols': maxc, 'rows': maxr, 'grid': grid, 'hexsides': hexsides, 'roads': roads, 'tracks': tracks, 'rails': rails}
with open(out, 'w') as fh:
    fh.write('// GENERATED by tools/map/assemble.py from the digitised map sections. Hand corrections go in mapfixes.js.\n')
    fh.write('// grid[c] is a string over r: ' + ', '.join(f'{v}={k}' for k, v in CODES.items()) + ', _=off map\n')
    fh.write('export const MAP_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(out, maxc, maxr, len(tiles), len(hexsides), len(roads), len(tracks), len(rails))
